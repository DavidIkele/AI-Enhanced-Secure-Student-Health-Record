DISCLAIMER = (
    "This suggestion is generated by a decision-support assistant from the "
    "symptoms entered by healthcare staff. It is informational only and is not "
    "a medical diagnosis. A qualified healthcare professional must confirm any "
    "condition and decide on treatment."
)


@dataclass(frozen=True)
class Condition:
    """One entry in the curated symptom knowledge base."""

    name: str
    patterns: tuple[str, ...]
    advice: str


@dataclass(frozen=True)
class SymptomResult:
    condition: str
    level: str
    score: float
    confidence: float
    advice: str


