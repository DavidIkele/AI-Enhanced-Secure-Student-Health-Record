"""Deterministic symptom-to-condition matcher for the staff symptom assessment.

The PHP backend sends the symptoms a student described (free text entered by a
doctor or nurse). This module scores those symptoms against a curated knowledge
base of common university-health-centre conditions and returns the most likely
matches ranked by score.

This is a decision-support assistant, NOT a medical diagnosis. It never sees
PII (names, reg numbers, emails) and stores nothing.

Design notes:
  * Each condition defines a list of keyword *patterns* (single words or short
    phrases). A pattern matches if it appears in the normalized text with word
    boundaries on both sides, so "fever" does not match inside "feverfew".
  * score = fraction of the condition's own patterns that matched (coverage).
  * level is derived from score thresholds; confidence is a bounded estimate.
  * An empty / unrecognized symptom set returns no conditions and a safe
    advisory — it never guesses.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

MODEL_VERSION = "symptom-matcher-1.0"

RISK_LEVELS = ("low", "moderate", "high")
LEVEL_HIGH = 0.55
LEVEL_MODERATE = 0.30

MAX_TEXT_LEN = 2000
