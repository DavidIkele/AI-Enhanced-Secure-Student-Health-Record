_compiled: dict[str, re.Pattern[str]] = {}


def _pattern_regex(pattern: str) -> re.Pattern[str]:
    if pattern not in _compiled:
        _compiled[pattern] = re.compile(
            r"(?<!\w)" + re.escape(pattern.lower()) + r"(?!\w)",
            re.IGNORECASE,
        )
    return _compiled[pattern]


def _normalize(text: str) -> str:
    """Lowercase and collapse whitespace; enforce a safe length."""
    text = " ".join(text.split())
    return text[:MAX_TEXT_LEN].lower()


def _match_conditions(text: str) -> tuple[list[SymptomResult], list[str]]:
    """Score the normalized text against the knowledge base.

    Returns (ranked results, deduplicated matched patterns).
    """
    norm = _normalize(text)
    if not norm:
        return [], []

    matched_symptoms: list[str] = []
    results: list[SymptomResult] = []

    for condition in KNOWLEDGE_BASE:
        hit_patterns: list[str] = []
        for pattern in condition.patterns:
            if _pattern_regex(pattern).search(norm):
                hit_patterns.append(pattern)
                if pattern not in matched_symptoms:
                    matched_symptoms.append(pattern)

        if not hit_patterns:
            continue

        score = round(len(hit_patterns) / len(condition.patterns), 4)
        if score >= LEVEL_HIGH:
            level = "high"
        elif score >= LEVEL_MODERATE:
            level = "moderate"
        else:
            level = "low"

        # Confidence blends how much of the condition profile matched with a
        # floor so a single clear symptom is not reported as 0 confidence.
        confidence = round(min(0.9, 0.10 + score * 0.80), 4)

        results.append(
            SymptomResult(
                condition=condition.name,
                level=level,
                score=score,
                confidence=confidence,
                advice=condition.advice,
            )
        )

    results.sort(key=lambda r: (r.score, r.confidence), reverse=True)
    return results[:MAX_CONDITIONS], matched_symptoms


def assess(text: str) -> dict:
    """Public entry point: returns the validated decision-support payload."""
    results, matched = _match_conditions(text)
    return {
        "conditions": [
            {
                "condition": r.condition,
                "level": r.level,
                "score": r.score,
                "confidence": r.confidence,
                "advice": r.advice,
            }
            for r in results
        ],
        "matched_symptoms": matched,
        "model_version": MODEL_VERSION,
        "disclaimer": DISCLAIMER,
    }
